android {
    // Internal Kotlin package stays com.example.iptvapp; the install/store
    // identity below is what the user actually sees.
    namespace = "com.example.iptvapp"
    compileSdk = 35

    // Supabase configuration from local.properties or CI env vars
    val supabaseUrl = System.getenv("SUPABASE_URL") ?: project.findProperty("supabase.url") as String? ?: ""
    val supabaseAnonKey = System.getenv("SUPABASE_ANON_KEY") ?: project.findProperty("supabase.anon.key") as String? ?: ""

    defaultConfig {
        applicationId = "com.tribaltv.app"
        minSdk = 26
        targetSdk = 34
        versionCode = 2
        versionName = "0.1.0"
        buildConfigField("String", "SUPABASE_URL", "\"$supabaseUrl\"")
        buildConfigField("String", "SUPABASE_ANON_KEY", "\"$supabaseAnonKey\"")
    }

    // Signing comes entirely from env vars (CI decodes the
    // TRIBAL_TV_KEYSTORE_B64 secret into a file and passes these). With none
    // set — local builds, or CI before the keystore secret exists — release
    // builds unsigned and debug falls back to AGP's default debug key.
    //
    // Blank is treated as absent: a CI secret that exists but is empty arrives
    // as "", and file("") would fail the build with a message about the
    // keystore rather than about the missing secret.
    val keystoreFile = System.getenv("TRIBAL_TV_KEYSTORE_FILE")?.takeIf { it.isNotBlank() }
    val keystorePassword = System.getenv("TRIBAL_TV_KEYSTORE_PASSWORD")?.takeIf { it.isNotBlank() }
    val keyAlias = System.getenv("TRIBAL_TV_KEY_ALIAS")?.takeIf { it.isNotBlank() }
    val keyPassword = System.getenv("TRIBAL_TV_KEY_PASSWORD")?.takeIf { it.isNotBlank() }

    val releaseSigning = if (keystoreFile != null && keystorePassword != null &&
        keyAlias != null && keyPassword != null
    ) {
        signingConfigs.create("release") {
            storeFile = file(keystoreFile)
            // The key is generated by scripts/rotate-signing-key.sh with
            // openssl, so it is PKCS#12, not JKS. apksigner's --ks-type
            // defaults to JKS, so this must be explicit.
            storeType = "PKCS12"
            storePassword = keystorePassword
            this.keyAlias = keyAlias
            this.keyPassword = keyPassword
        }
    } else {
        null
    }

    buildTypes {
        debug {
            // Google Sign-In compares the APK's signing certificate against the
            // SHA-1 registered in the OAuth client. AGP mints a fresh debug
            // keystore on every clean CI runner, so a debug-signed build would
            // never match and sign-in would fail with DEVELOPER_ERROR on the
            // exact artifact we install. Signing debug with the release key
            // gives both variants one identity.
            //
            // Only when the release key is present: assigning null here would
            // make debug unsigned rather than fall back to AGP's default key.
            if (releaseSigning != null) {
                signingConfig = releaseSigning
            }
        }
        release {
            isMinifyEnabled = false
            if (releaseSigning != null) {
                signingConfig = releaseSigning
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        // defaultConfig above sets SUPABASE_URL / SUPABASE_ANON_KEY via
        // buildConfigField. AGP 8 defaults this to false and fails at
        // configuration time -- before compiling anything -- if a field is
        // declared without it.
        buildConfig = true
    }

    testOptions {
        unitTests {
            // Robolectric simulates the Android framework inside the JVM
            // unit-test task and needs the merged resources/assets to do it.
            // Used for the real Room 3 -> 4 migration test.
            isIncludeAndroidResources = true
        }
    }
}

